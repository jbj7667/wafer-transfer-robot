# arm_bench 벨트·풀리 재계산 (L=180). 실행: python -I belt.py -> belt_out.md
import math
p = 2.0
STD = [200, 252, 280, 300, 310, 320, 360, 400, 404, 440, 488, 610]  # 2GT-6 폐루프 표준 길이 후보 [확인필요]
def pd(T): return p * T / math.pi
def blen(T1, T2, C):
    D, d = pd(T1), pd(T2)
    return 2 * C + math.pi * (D + d) / 2 + (D - d) ** 2 / (4 * C)
def solveC(T1, T2, Lt):
    lo, hi = 20.0, 600.0
    for _ in range(80):
        m = (lo + hi) / 2
        if blen(T1, T2, m) < Lt: lo = m
        else: hi = m
    return (lo + hi) / 2
def wrap(T1, T2, C):
    D, d = pd(T1), pd(T2)
    a = 180 - 2 * math.degrees(math.asin(abs(D - d) / (2 * C)))
    return a, a / 360 * min(T1, T2)
o = []; P = o.append
P("# Bench 벨트·풀리 재계산 (L=180, GT2 6mm 피치 2mm)\n")
P("## 1. 링크 연동 벨트 (C=180, 2:1 / 1:2)\n")
P("| Ts:Te | PD(mm) | 계산 길이 | 이빨수(정수) | 그 N의 C | 접촉각 | 접촉이빨 | 가장 가까운 표준 폐루프 | 그 길이의 C | C 변화(mm) |")
P("|---|---|---|---|---|---|---|---|---|---|")
for Ts, Te in ((30, 15), (40, 20), (44, 22), (46, 23), (52, 26), (54, 27), (56, 28), (60, 30)):
    Lb = blen(Ts, Te, 180); N = round(Lb / p)
    s = min(STD, key=lambda x: abs(x - Lb))
    a, nt = wrap(Ts, Te, 180)
    P(f"| {Ts}:{Te} | {pd(Ts):.1f}/{pd(Te):.1f} | {Lb:.1f} | {N} ({N*p:.0f}) | {solveC(Ts,Te,N*p):.2f} | {a:.0f} | {nt:.1f} | {s} ({s//2}T) | {solveC(Ts,Te,s):.2f} | {solveC(Ts,Te,s)-180:+.2f} |")
P("\n선정: **52T:26T + 폐루프 440 mm(220T)**: C=%.2f mm (설계 180 대비 +%.2f mm). 링크 슬롯/텐셔너 행정 ±3 mm 안. 접촉 이빨 12.7 (>=6). 팔꿈치 26T 이므로 슬랙 증폭 L/r_e=21.7 (r_e=8.28)." % (solveC(52,26,440), solveC(52,26,440)-180))
P("대안: 40:20 은 420 mm 가 표준 길이가 아니고, 60:30 은 450 mm 도 표준이 아니므로(440 은 C=%.1f 로 -%.1f mm, 슬롯 범위 밖) 제외." % (solveC(60,30,440), 180-solveC(60,30,440)))
P("표준 길이가 없을 때(오픈 벨트 + 클램프): 정수 이빨 219T (438 mm) -> C=%.2f, 클램프 이음은 이빨 6개 이상 물림.\n" % solveC(52,26,438))
P("벨트1(어깨 52T -> 팔꿈치 26T, 링크1 안), 벨트2(팔꿈치 26T -> 손목 52T, 링크2 안): **같은 440 mm 2개**.\n")
P("## 2. θ 회전대 감속 (보유 310 mm = 155T)\n")
P("| 풀리 | PD | C(mm) | 접촉각 | 접촉이빨 | 대풀리 플랜지 외경 |")
P("|---|---|---|---|---|---|")
for t1, t2 in ((20, 60),):
    C = solveC(t1, t2, 310); a, nt = wrap(t1, t2, C)
    P(f"| {t1}T:{t2}T (3:1) | {pd(t1):.2f}/{pd(t2):.2f} | {C:.2f} | {a:.0f} | {nt:.1f} | {pd(t2)+3:.1f} |")
P("\n## 3. R(어깨) 구동: 같은 20T:60T, C=114.3 -> **폐루프 310 mm 1개 추가 구매** (arm_option §2.3 의 R 3:1 오픈 벨트를 폐루프로 대체, 클램프 불필요)\n")
P("## 4. 슬랙 증폭 (팔끝 변위 = L*s/r_e, L=180)\n")
P("| 팔꿈치 T | r_e | 증폭 | s=0.1 | s=0.2 |")
P("|---|---|---|---|---|")
for Te in (20, 26, 30):
    r = pd(Te) / 2
    P(f"| {Te} | {r:.2f} | {180/r:.1f} | {180*0.1/r:.1f} | {180*0.2/r:.1f} |")
P("\n## 5. 풀리 치수 (PD / 이빨끝 OD / 플랜지 외경=PD+3)\n")
P("| T | PD | OD | 플랜지 |")
P("|---|---|---|---|")
for T in (20, 26, 52, 60):
    P(f"| {T} | {pd(T):.2f} | {pd(T)-0.76:.2f} | {pd(T)+3:.1f} |")
P("\n## 6. 구매 목록 (벨트·풀리·체결)\n")
P("| 품목 | 수량 | 용도 |")
P("|---|---|---|")
for r in ("GT2 6mm 폐루프 440 mm (220T) | 3 (사용 2 + 예비 1) | 링크 연동 벨트1·2",
          "GT2 6mm 폐루프 310 mm (155T) | 1 추가 (보유 1은 θ) (예비 1 권장 = 2) | R 구동",
          "GT2 6mm 오픈 벨트 | 1 m (선택) | 폐루프를 못 구할 때 438 mm + 클램프 2쌍",
          "608ZZ | 10 (사용 7: θ축 2, 어깨허브 2, 팔꿈치허브 2, 손목 1 + 아이들러 2~3) | 베어링",
          "M8 나사봉(전산) 1 m 또는 M8x120 / x60 / x40 볼트 | 축 3개: 어깨·θ 공용 축 120, 팔꿈치 60, 손목 45 | 고정축",
          "M8 너트·와셔 | 약 14 / 14 | 축 체결, 스페이서",
          "M3 세트스크루 8~10 mm | 8 | 풀리 고정",
          "M3x10 / M3x16 나사 + 너트 | 각 40 / 20 | 뚜껑, 허브-링크 체결, 모터",
          "M4 열삽입너트 (또는 M5) | 2 | 테이블 고정 클램프 위치",
          "GT2 20T 알루미늄 풀리 보어 5 mm (선택) | 2 | 인쇄 20T 대신(모터 풀리 정밀도)"):
    P("| " + r + " |")
open('belt_out.md', 'w', encoding='utf-8').write('\n'.join(o))
print('\n'.join(o))
