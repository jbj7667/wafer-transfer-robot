# GT2 6mm 벨트/풀리 계산. 실행: python -I belt.py (출력 belt_out.md)
import math
p = 2.0  # GT2 피치
out = []
P = out.append


def pd(T):
    return p * T / math.pi


def blen(T1, T2, C):
    D, d = pd(T1), pd(T2)
    return 2 * C + math.pi * (D + d) / 2 + (D - d) ** 2 / (4 * C)


def solveC(T1, T2, Ltarget):
    lo, hi = 20.0, 600.0
    for _ in range(80):
        m = (lo + hi) / 2
        if blen(T1, T2, m) < Ltarget:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


def wrap(T1, T2, C):
    D, d = pd(T1), pd(T2)
    a = 180 - 2 * math.degrees(math.asin(abs(D - d) / (2 * C)))
    return a, a / 360 * min(T1, T2)


P("## B1. 링크 연동 벨트 (C=205): 2:1 / 1:2 쌍 후보")
P("벨트1: 어깨 고정풀리(Ts) -> 팔꿈치 풀리(Te, 링크2에 고정), Ts/Te=2. 벨트2: 팔꿈치(링크1에 고정, Te) -> 손목(Tw), Tw/Te=2.")
P("| Ts:Te | PD(mm) | 벨트 길이(mm) | 이빨 수(계산) | 정수 이빨 N | 그 N일 때 C(mm) | 소풀리 접촉각(deg) | 접촉 이빨 |")
P("|---|---|---|---|---|---|---|---|")
for Ts, Te in ((30, 15), (36, 18), (40, 20), (52, 26), (60, 30)):
    Lb = blen(Ts, Te, 205)
    N = round(Lb / p)
    C2 = solveC(Ts, Te, N * p)
    a, nt = wrap(Ts, Te, 205)
    P(f"| {Ts}:{Te} | {pd(Ts):.1f}/{pd(Te):.1f} | {Lb:.1f} | {Lb/p:.1f} | {N} ({N*p} mm) | {C2:.2f} | {a:.0f} | {nt:.1f} |")
P("")
P("표준 폐루프 GT2 6mm 길이 후보(상점 재고는 확인필요): 200, 280, 300, 400, 488, 610. C=205 고정이면 길이 = 410 + (T1+T2) + 소량 이므로")
P("| 폐루프 길이 | 필요 T1+T2 (C=205) | 2:1 쌍 | 판정 |")
P("|---|---|---|---|")
for Lc in (400, 470, 488, 610):
    tsum = Lc - 410
    if tsum < 30:
        P(f"| {Lc} | {tsum} | - | 불가(풀리 너무 작음) |")
    else:
        t2 = tsum / 3
        P(f"| {Lc} | {tsum} | {2*t2:.0f}:{t2:.0f} | {'정수 2:1 가능' if abs(t2-round(t2))<0.05 else '정수비 불가'} |")
P("")
P("## B2. 보유 폐루프 310mm (155T) 활용: 소풀리:대풀리 후보의 축간거리")
P("| 소:대 | 비 | PD(mm) | 축간거리 C(mm) | 소풀리 접촉각 | 접촉 이빨 | 대풀리 외경(+1.4) |")
P("|---|---|---|---|---|---|---|")
for t1, t2 in ((20, 60), (16, 48), (15, 45), (20, 40), (16, 64), (20, 80)):
    C = solveC(t1, t2, 310)
    a, nt = wrap(t1, t2, C)
    P(f"| {t1}:{t2} | {t2/t1:.1f}:1 | {pd(t1):.1f}/{pd(t2):.1f} | {C:.1f} | {a:.0f} | {nt:.1f} | {pd(t2)+1.4:.1f} |")
P("")
P("권장: θ 회전대 구동에 20T:60T (C=114.3). 폐루프라 클램프 이음이 없어 회전대 반복성에 유리. 모터 슬롯 +-3mm로 장력 조정.")
P("")
P("## B3. 벨트 슬랙 -> 팔끝 오차 (총 슬랙 s mm, 벨트1: 링크2 상대각 s/r_e)")
P("| Te(T) | r_e(mm) | 증폭 L/r_e | s=0.1 | s=0.2 | s=0.4 |")
P("|---|---|---|---|---|---|")
for Te in (15, 18, 20, 26, 30):
    r = pd(Te) / 2
    P(f"| {Te} | {r:.2f} | {205/r:.1f} | {205*0.1/r:.1f} | {205*0.2/r:.1f} | {205*0.4/r:.1f} |")
P("해석: 팔끝 변위 = L*s/r_e (증폭 21~43배). 목표 팔끝 +-5mm를 지키려면 총 슬랙 s를 0.1~0.15mm 이하(26T 쌍)로 눌러야 함. 인쇄 풀리 단독으로는 어려우므로 선장력+한 방향 접근 필수.")
P("완화: (1) 한 방향 접근(항상 같은 방향으로 도달), (2) 벨트 선장력 10~15N, (3) 가능하면 알루미늄 GT2 풀리 구매, (4) 큰 풀리(26T 이상)")
P("")
P("## B4. 장력 측정(중앙 처짐법) 스팬 205mm: 처짐 = F*span/(4T)")
P("| 장력 T(N) | 중앙에 1N(약 100g) 매달 때 처짐(mm) |")
P("|---|---|")
for T in (5, 8, 12, 15, 20):
    P(f"| {T} | {1*205/(4*T):.1f} |")
P("목표 T=10~15N(가정) -> 100g 추 처짐 3.4~5.1mm. 축 하중은 약 2T=20~30N (608 베어링 충분).")
P("")
P("## B5. 풀리 치수 (PD / OD=PD-0.76 / 플랜지 포함 폭)")
P("| T | PD | OD(이빨 끝) |")
P("|---|---|---|")
for T in (15, 16, 18, 20, 26, 30, 40, 52, 60):
    P(f"| {T} | {pd(T):.2f} | {pd(T)-0.76:.2f} |")

P("")
P("## B6. 링크 L=180 변형 (C=180) 벨트")
P("| Ts:Te | 벨트 길이(mm) | 이빨 | 정수 N일 때 C |")
P("|---|---|---|---|")
for Ts, Te in ((40, 20), (52, 26), (60, 30)):
    Lb = blen(Ts, Te, 180)
    N = round(Lb / p)
    P(f"| {Ts}:{Te} | {Lb:.1f} | {Lb/p:.1f} -> {N} | {solveC(Ts, Te, N*p):.2f} |")
P("폐루프 길이 = 360 + (T1+T2): 420(40:20), 438(52:26), 450(60:30). 표준 재고 확인필요.")
open('belt_out.md', 'w', encoding='utf-8').write('\n'.join(out))
print('\n'.join(out))
